  var SKIP_TAGS = { PRE: 1, CODE: 1, SCRIPT: 1, STYLE: 1, TEXTAREA: 1, KBD: 1, SAMP: 1 };
  var SKIP_CLASS = /(^|\s)(hashgrid|doc-sheet__code|no-i18n|chat-time|chat-source|chat-who)(\s|$)/;

  var lang = function () {
    return (document.documentElement.lang || "en") === "hi" ? "hi" : "en";
  };

  function translateString(raw) {
    var key = String(raw || "").trim();
    if (!key || key.length < 2) return null;
    if (DICT[key]) return DICT[key];
    for (var i = 0; i < PATTERNS.length; i++) {
      var m = key.match(PATTERNS[i][0]);
      if (m) return PATTERNS[i][1](m);
    }
    return null;
  }

  function skip(node) {
    var el = node.parentElement;
    while (el) {
      if (SKIP_TAGS[el.tagName]) return true;
      var cls = el.getAttribute && el.getAttribute("class");
      if (cls && SKIP_CLASS.test(cls)) return true;
      if (el.hasAttribute && el.hasAttribute("data-no-i18n")) return true;
      if (el.getAttribute && el.getAttribute("data-i18n")) return true;
      el = el.parentElement;
    }
    return false;
  }

  var stats = { nodes: 0, attrs: 0, misses: 0 };

  function applyTextNode(node) {
    if (skip(node)) return;
    var raw = node.nodeValue;
    if (!raw || !/[A-Za-z]{3}/.test(raw)) return;
    var out = translateString(raw);
    if (out === null) return;
    var lead = (raw.match(/^\s*/) || [""])[0];
    var trail = (raw.match(/\s*$/) || [""])[0];
    node.nodeValue = lead + out + trail;
    stats.nodes++;
  }

  var ATTRS = ["placeholder", "title", "aria-label", "alt"];

  function applyAttrs(el) {
    for (var i = 0; i < ATTRS.length; i++) {
      var v = el.getAttribute && el.getAttribute(ATTRS[i]);
      if (!v || !/[A-Za-z]{3}/.test(v)) continue;
      var out = translateString(v);
      if (out !== null && out !== v) {
        el.setAttribute(ATTRS[i], out);
        stats.attrs++;
      }
    }
  }

  function apply(root) {
    if (lang() !== "hi") return;
    var host = root || document.body;
    if (!host) return;
    try {
      var walker = document.createTreeWalker(host, NodeFilter.SHOW_TEXT, null);
      var batch = [];
      var n;
      while ((n = walker.nextNode())) batch.push(n);
      for (var i = 0; i < batch.length; i++) applyTextNode(batch[i]);
      var els = host.querySelectorAll ? host.querySelectorAll("*") : [];
      for (var j = 0; j < els.length; j++) applyAttrs(els[j]);
      if (host.nodeType === 1) applyAttrs(host);
    } catch (e) {
      /* translation is an enhancement, never a blocker */
    }
  }

  /* Content rendered later (faculty, finance, graph, network, toasts). */
  var pending = null;
  function schedule() {
    if (lang() !== "hi" || pending) return;
    pending = window.requestAnimationFrame(function () {
      pending = null;
      apply(document.body);
    });
  }

