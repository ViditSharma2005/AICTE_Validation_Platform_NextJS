function renderCrumbs(parts) {
  const el = $("#breadcrumbs");
  if (!el) return;
  const head = parts[0] || "";
  const trail = [[t("navHome"), "#/"]];
  const add = (label, href) => trail.push([label, href || null]);
  if (!head || head === "login") add(user ? t("navDashboard") : t("signIn"));
  else if (head === "college") { add("My Applications", "#/college"); if (parts[1] === "app") add("Application File"); }
  else if (head === "officer") { add("Work Queue", "#/officer"); if (parts[1] === "app") add("Application File"); }
  else if (head === "doc") add("Document");
  else if (head === "checklist") add(t("navChecklist"));
  else if (head === "documents") add(t("navDocuments"));
  else if (head === "scenarios") add(t("navReports"));
  else if (head === "alerts") add(t("navAlerts"));
  else if (head === "audit") add(t("navAudit"));
  else if (head === "admin") add(t("navAdmin"));
  else if (head === "help") add(t("navHelp"));
  else if (head === "search") add("Search Results");
  else add(head);
  el.innerHTML = trail.map(([label, href], i) =>
    i === trail.length - 1
      ? `<li><span aria-current="page">${esc(label)}</span></li>`
      : `<li><a href="${href}">${esc(label)}</a></li>`).join("");
}
function buildNav() {
  const nav = $("#main-nav"), right = $("#top-right");
  if (!nav || !right) return;
  const parts = location.hash.replace(/^#\/?/, "").split("/").filter(Boolean);
  const head = parts[0] || "";
  const link = (href, label, active) =>
    `<a href="#/${href}" class="${active ? "active" : ""}"${active ? ' aria-current="page"' : ""}>${label}</a>`;
  const dash = !user ? "login" : user.role.startsWith("College") ? "college"
    : user.role === "System Admin" ? "admin" : "officer";
  const dashActive = head === "college" || head === "officer" || head === "doc" || (!head && !!user);
  let links = link("", t("navHome"), !head)
    + link(dash, t("navDashboard"), dashActive)
    + link("checklist", t("navChecklist"), head === "checklist")
    + (user ? link("documents", t("navDocuments"), head === "documents") : "")
    + link("scenarios", t("navReports"), head === "scenarios")
    + (user ? link("alerts", t("navAlerts"), head === "alerts") + link("audit", t("navAudit"), head === "audit") : "")
    + link("help", t("navHelp"), head === "help")
    + (user && user.role === "System Admin" ? link("admin", t("navAdmin"), head === "admin") : "");
  nav.innerHTML = links;
  nav.classList.remove("open");
  const tog = $("#nav-toggle");
  if (tog) tog.setAttribute("aria-expanded", "false");
  right.innerHTML = user
    ? `<span>${esc(user.name)}<br><span class="faint" style="font-size:.72rem;text-transform:uppercase;letter-spacing:.06em">${esc(user.role)}</span></span>
       <button class="linkbtn" onclick="A.logout()">${t("signOut")}</button>`
    : `<a class="btn small primary" href="#/login">${t("signIn")}</a>`;
  renderCrumbs(parts);
  const ticker = $("#ticker");
  if (ticker) {
    const show = !head || head === "login"
      || (head === "officer" && !parts[1]) || (head === "college" && !parts[1]);
    ticker.hidden = !show;
  }
}

