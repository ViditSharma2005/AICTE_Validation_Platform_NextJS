function vtag(status) {
  const s = status || "Not run";
  const cls = s === "Verified" ? "verified" : s === "Mismatch detected" ? "mismatch" :
    s === "Expired" ? "expired" : s.startsWith("Declared") ? "declared" :
    s === "Manual review required" ? "manual" : "pending";
  return `<span class="tag ${cls}">${esc(s)}</span>`;
}
