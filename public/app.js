async function loadGraph(appId) {
  const slot = $("#graph-slot"); if (!slot) return;
  try {
    const g = await api(`/applications/${appId}/graph`);
    const W = 860, H = 400, cx = 150, cy = 200;
    const self = g.nodes.find((n) => n.self) || g.nodes[0];
    const others = g.nodes.filter((n) => n !== self);
    // Column layout: this college | shared things (people, land, images) | other colleges.
    // Fixed columns keep labels from colliding the way a radial layout does.
    const pos = { [self.id]: [cx, cy] };
    const spread = (arr, x, y0, y1) => arr.forEach((n, i) => {
      pos[n.id] = [x, arr.length === 1 ? cy : y0 + ((y1 - y0) * i) / (arr.length - 1)];
    });
    spread(others.filter((n) => n.kind !== "college" && n.kind !== "trust"), 450, 115, 325);
    spread(others.filter((n) => n.kind === "college"), 718, 105, 335);
    others.filter((n) => n.kind === "trust").forEach((n) => { pos[n.id] = [450, 52]; });
    const edges = g.edges.filter((e) => pos[e.a] && pos[e.b]).map((e) => {
      const [x1, y1] = pos[e.a], [x2, y2] = pos[e.b];
      return `<line class="graph-edge ${e.alert ? "alert-edge" : ""}" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"></line>
        <text class="edge-txt" x="${(x1 + x2) / 2}" y="${(y1 + y2) / 2 - 4}" text-anchor="middle">${esc(e.label)}</text>`;
    }).join("");
    const nodes = g.nodes.map((n) => {
      const [x, y] = pos[n.id];
      const label = n.label.length > 30 ? n.label.slice(0, 29) + "…" : n.label;
      return `<circle class="${n.self ? "node-self" : "node-circle"}" cx="${x}" cy="${y}" r="${n.self ? 9 : 6}"></circle>
        <text class="node-txt" x="${x}" y="${y - 13}" text-anchor="middle">${esc(label)}</text>
        <text class="edge-txt" x="${x}" y="${y + 20}" text-anchor="middle">${esc(n.kind)}</text>`;
    }).join("");
    slot.innerHTML = `
      <p class="soft">${esc(g.note)} The table under the drawing carries the same links in words, with routes into the other files.</p>
      <div class="chart-wrap" style="margin-top:12px"><svg viewBox="0 0 ${W} ${H}" width="100%" role="img" aria-label="Graph of people, land, trusts and images shared between this college and others">${edges}${nodes}</svg></div>
      <div class="table-scroll" style="margin-top:14px"><table><thead><tr><th>From</th><th>Link</th><th>To</th><th>Type</th><th></th></tr></thead><tbody>
      ${g.edges.map((e) => {
        const A = g.nodes.find((n) => n.id === e.a), B = g.nodes.find((n) => n.id === e.b);
        return `<tr><td>${esc(A?.label || e.a)}</td><td>${esc(e.label)}</td><td>${esc(B?.label || e.b)}</td>
        <td>${e.alert ? `<span class="tag mismatch">Reuse to examine</span>` : `<span class="tag declared">Context</span>`}</td>
        <td>${e.application_id && e.application_id !== appId ? `<a href="#/officer/app/${e.application_id}">Other file →</a>` : e.document_id ? `<a href="#/doc/${e.document_id}">Document →</a>` : ""}</td></tr>`;
      }).join("")}
      </tbody></table></div>`;
  } catch (e) { slot.innerHTML = errBox(e.message); }
}

