async function api(path, opts = {}) {
  const res = await fetch("/api" + path, {
    method: opts.method || "GET",
    headers: { "Content-Type": "application/json", ...(token ? { Authorization: "Bearer " + token } : {}), ...(opts.headers || {}) },
    body: opts.body ? JSON.stringify(opts.body) : opts.rawBody,
  });
  let data = null;
  try { data = await res.json(); } catch (e) { /* non-JSON */ }
  if (!res.ok) throw new Error((data && data.detail) || ("Request failed (" + res.status + ")"));
  return data;
}
async function apiForm(path, formData) {
  const res = await fetch("/api" + path, { method: "POST", headers: token ? { Authorization: "Bearer " + token } : {}, body: formData });
  const data = await res.json().catch(() => null);
  if (!res.ok) throw new Error((data && data.detail) || ("Upload failed (" + res.status + ")"));
  return data;
}

