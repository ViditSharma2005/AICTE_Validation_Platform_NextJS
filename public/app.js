function checklistProgress(detail) {
  // progress over the deep slice; full 70-item load shown as group counts
  const filed = new Set(detail.documents.filter((d) => d.status !== "Returned for fix").map((d) => d.checklist_code));
  const groups = {};
  (META?.checklist || []).forEach((it) => {
    groups[it.group_code] = groups[it.group_code] || { total: 0, done: 0 };
    groups[it.group_code].total++; if (filed.has(it.code)) groups[it.group_code].done++;
  });
  const names = { A: "Legal & trust", B: "Land & building", C: "Financial", D: "Approvals", E: "Faculty & HR", F: "Infrastructure", G: "Website disclosure", H: "Committees", I: "Accreditation" };
  return Object.entries(groups).map(([g, v]) => `
    <div class="progressline"><span class="mono" style="width:170px;font-size:.78rem">${g} · ${names[g] || ""}</span>
    <span class="meter ${v.done === v.total ? "" : "medium"}" role="img" aria-label="${v.done} of ${v.total} filed"><i style="width:${v.total ? (v.done / v.total) * 100 : 0}%"></i></span>
    <span class="mono soft" style="font-size:.78rem">${v.done}/${v.total}</span></div>`).join("");
}

